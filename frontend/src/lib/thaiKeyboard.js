/**
 * แปลงข้อความที่พิมพ์ผิดภาษา (แป้นไทยเกษมณี) กลับเป็นอังกฤษ
 *
 * เครื่องสแกนบาร์โค้ดทำงานเหมือนคีย์บอร์ด — มันส่ง "ปุ่ม" ไม่ได้ส่ง "ตัวอักษร"
 * ถ้าตอนยิง Windows อยู่ภาษาไทย บาร์โค้ด OD20260925-0028 จะกลายเป็น ฯฏ/จ/ุจต/ถขจจ/ค
 * พนักงานต้องคอยสลับภาษาก่อนยิงทุกครั้งซึ่งลืมแน่ เลยดักแปลงกลับให้ที่ระบบแทน
 */

/** ปุ่มอังกฤษ -> ตัวอักษรที่ได้เมื่อแป้นเป็นภาษาไทย (เกษมณี) */
const EN_TO_TH = {
  '1': 'ๅ', '2': '/', '3': '_', '4': 'ภ', '5': 'ถ', '6': 'ุ', '7': 'ึ', '8': 'ค', '9': 'ต', '0': 'จ',
  '-': 'ข', '=': 'ช',
  q: 'ๆ', w: 'ไ', e: 'ำ', r: 'พ', t: 'ะ', y: 'ั', u: 'ี', i: 'ร', o: 'น', p: 'ย', '[': 'บ', ']': 'ล',
  a: 'ฟ', s: 'ห', d: 'ก', f: 'ด', g: 'เ', h: '้', j: '่', k: 'า', l: 'ส', ';': 'ว', "'": 'ง',
  z: 'ผ', x: 'ป', c: 'แ', v: 'อ', b: 'ิ', n: 'ื', m: 'ท', ',': 'ม', '.': 'ใ', '/': 'ฝ',

  // กดพร้อม Shift
  Q: '๐', W: '"', E: 'ฎ', R: 'ฑ', T: 'ธ', Y: 'ํ', U: '๊', I: 'ณ', O: 'ฯ', P: 'ญ',
  A: 'ฤ', S: 'ฆ', D: 'ฏ', F: 'โ', G: 'ฌ', H: '็', J: '๋', K: 'ษ', L: 'ศ',
  Z: '(', X: ')', C: 'ฉ', V: 'ฮ', B: 'ฺ', N: '์', M: '?',
};

/** ตัวอักษรไทย -> ปุ่มอังกฤษ (กลับด้านจากตารางบน) */
const TH_TO_EN = Object.fromEntries(Object.entries(EN_TO_TH).map(([en, th]) => [th, en]));

const HAS_THAI = /[฀-๿]/;

/**
 * ถ้าข้อความมีตัวอักษรไทยปน = ยิงบาร์โค้ดตอนแป้นเป็นภาษาไทย ให้แปลงกลับทั้งชุด
 * ถ้าไม่มีตัวไทยเลยก็คืนค่าเดิม ไม่ไปยุ่งกับข้อความที่ถูกต้องอยู่แล้ว
 */
export function fixThaiKeyboard(text) {
  const s = String(text);
  if (!HAS_THAI.test(s)) return s;
  return [...s].map((ch) => TH_TO_EN[ch] ?? ch).join('');
}
